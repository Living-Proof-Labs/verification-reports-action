def snapshot(root):
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}


@pytest.fixture
def case(tmp_path):
    # Explicit local integration inputs. Not downloaded or regenerated by this test.
    source = os.environ.get("VIEWER_REPORT_FIXTURE")
    command = os.environ.get("VIEWER_REPORTER_COMMAND")
    asset = os.environ.get("VIEWER_RELEASE_ASSET")
    if not all((source, command, asset)):
        pytest.skip("installed candidate integration requires explicit verified inputs")
    source = Path(source)
    for name in ("regenerated-report.json", "health.json"):
        shutil.copyfile(
            source / name, tmp_path / ("report.json" if name.startswith("regenerated") else name)
        )
    raw = Path(asset).read_bytes()
    from livingproof_capability_report import render

    (tmp_path / "index.html").write_text(
        render(json.loads((tmp_path / "report.json").read_bytes()), "html")
    )
    write_published_checksums(tmp_path)
    pin = dict(
        evaluator=dict(
            id="livingproof-health", version="1.2.0", publisher="Living Proof Labs", kind="advisory"
        ),
        evaluator_repository="Living-Proof-Labs/livingproof-evaluator-health",
        declaration_line="Living-Proof-Labs/livingproof-evaluator-health@v1.2.0/livingproof-evaluator.json",
        recording_format="livingproof-evaluator-health/1",
        bytes=raw,
        viewer_sha256=hashlib.sha256(raw).hexdigest(),
    )
    return tmp_path, [pin], (command,)


def test_installed_candidate_owns_output_and_preserves_portable_bytes(case):
    root, pins, command = case
    before = snapshot(root)
    assert render_fresh(root, pins, command=command)
    assert (root / "report.json").read_bytes() == before["report.json"]
    assert (root / "health.json").read_bytes() == before["health.json"]
    text = (root / "index.html").read_text()
    assert text.count("<iframe ") == 1 and "Recorded data</a>" in text
    assert (root / "trusted-viewer/data/recording.json").read_bytes() == before["health.json"]


@pytest.mark.parametrize(
    "fault", ["digest", "trial", "report", "manifest", "executable", "missing"]
)
def test_refusal_has_no_output_changes(case, fault):
    root, pins, command = case
    report = json.loads((root / "report.json").read_bytes())
    if fault == "digest":
        (root / "health.json").write_bytes(b"tampered")
    elif fault == "trial":
        data = json.loads((root / "health.json").read_bytes())
        data["trials"][0]["trial"]["index"] = True
        raw = json.dumps(data).encode()
        (root / "health.json").write_bytes(raw)
        report["source_bundle"]["assessment"]["advisory_results"]["livingproof-health"]["advisory"][
            "details_file"
        ]["sha256"] = hashlib.sha256(raw).hexdigest()
        from livingproof_capability_report.core import digest

        report["source_bundle_sha256"] = digest(report["source_bundle"])
        (root / "report.json").write_text(json.dumps(report))
    elif fault == "report":
        report["source_bundle_sha256"] = "0" * 64
        (root / "report.json").write_text(json.dumps(report))
    elif fault == "executable":
        pins[0]["bytes"] = b"bad"
    elif fault == "missing":
        (root / "health.json").unlink()
    if fault != "manifest":
        write_published_checksums(root)
    else:
        (root / "unrelated-evidence.json").write_text("unlisted")
    before = snapshot(root)
    with pytest.raises((SiteError, ValueError)):
        render_fresh(root, pins, command=command)
    assert snapshot(root) == before


